#!/usr/bin/env node
// Model-checks SpendCap.tla against the built src/spend.ts. Usage:
//   node .cursor/skills/spend-cap-model/check.mjs            every config, compared with RUNS
//   node .cursor/skills/spend-cap-model/check.mjs FILE.cfg   one config, which must hold
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const TLA = { version: "1.7.4", sha256: "936a262061c914694dfd669a543be24573c45d5aa0ff20a8b96b23d01e050e88" };
// `expect` names the invariant an open finding breaks (SKILL.md, Findings); null means every invariant holds.
const RUNS = [
  { cfg: "SpendCapOnePass.cfg", expect: null },
  { cfg: "SpendCap.cfg", expect: "LandedStaysCounted" },
];
// The generated tables must cover the constants in every config; SpendCap.tla ASSUMEs it.
const RANGES = { spent: [0, 8], usd: [1, 3], cap: [0, 8], agedTxs: 4 };

function fail(message) {
  console.error(`spend-cap-model: ${message}`);
  process.exit(2);
}

function range([low, high]) {
  return Array.from({ length: high - low + 1 }, (_, index) => low + index);
}

function* counts(slots, total) {
  if (slots === 0) return yield [];
  for (let first = 0; first <= total; first += 1) for (const rest of counts(slots - 1, total - first)) yield [first, ...rest];
}

function* orders(items) {
  if (items.length <= 1) return yield items;
  const seen = new Set();
  for (const [index, item] of items.entries()) {
    if (seen.has(item)) continue;
    seen.add(item);
    for (const rest of orders([...items.slice(0, index), ...items.slice(index + 1)])) yield [item, ...rest];
  }
}

const tla = (value) => (typeof value === "string" ? `"${value}"` : String(value));

async function spendCode() {
  const spend = await import(pathToFileURL(path.join(repo, "dist/src/spend.js")).href);
  const reserve = [];
  for (const existing of ["none", "reserved", "committed", "released"]) {
    for (const spent of range(RANGES.spent)) {
      for (const usd of range(RANGES.usd)) {
        for (const cap of range(RANGES.cap)) {
          const decision = spend.reserveDecision({ existing: existing === "none" ? null : existing, spent, usd, cap });
          reserve.push(`<<${[existing, spent, usd, cap, decision].map(tla).join(", ")}>>`);
        }
      }
    }
  }
  // recordTx writes signed_tx before spend_journal.tx_hash, so a row with no signed transaction has no tx_hash.
  const row = { idempotencyKey: "k", txHash: null, chainKey: null, legacy: false };
  const names = ["landed", "reverted", "expired", "pending", null];
  const reconcile = [];
  for (const vector of counts(names.length, RANGES.agedTxs)) {
    const outcomes = vector.flatMap((n, index) => Array(n).fill(names[index]));
    const decision = spend.reconcileDecision(row, outcomes);
    for (const order of orders(outcomes)) {
      if (spend.reconcileDecision(row, order) !== decision) fail(`reconcileDecision now depends on the order of outcomes (${JSON.stringify(order)}). The model counts outcomes; model the order first.`);
    }
    reconcile.push(`<<${[...vector, decision].map(tla).join(", ")}>>`);
  }
  return `---------------------------- MODULE SpendCode ----------------------------
\\* Generated by check.mjs from reserveDecision and reconcileDecision in src/spend.ts. Do not edit.
EXTENDS Naturals
SpentRange == ${RANGES.spent.join("..")}
UsdRange == ${RANGES.usd.join("..")}
CapRange == ${RANGES.cap.join("..")}
MaxAgedTxs == ${RANGES.agedTxs}
ReserveRows == {
  ${reserve.join(",\n  ")}}
ReconcileRows == {
  ${reconcile.join(",\n  ")}}
ReserveTable == [r \\in {"none", "reserved", "committed", "released"} \\X SpentRange \\X UsdRange \\X CapRange |->
    (CHOOSE w \\in ReserveRows : <<w[1], w[2], w[3], w[4]>> = r)[5]]
ReserveDecision(existing, spent, usd, cap) == ReserveTable[<<existing, spent, usd, cap>>]
ReconcileTable == [r \\in {<<w[1], w[2], w[3], w[4], w[5]>> : w \\in ReconcileRows} |->
    (CHOOSE w \\in ReconcileRows : <<w[1], w[2], w[3], w[4], w[5]>> = r)[6]]
ReconcileDecision(landed, reverted, expired, pending, unknown) == ReconcileTable[<<landed, reverted, expired, pending, unknown>>]
=============================================================================
`;
}

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function tlaJar() {
  const dir = path.join(process.env.XDG_CACHE_HOME ?? path.join(os.homedir(), ".cache"), "whale");
  const jar = path.join(dir, `tla2tools-${TLA.version}.jar`);
  if (existsSync(jar) && sha256(readFileSync(jar)) === TLA.sha256) return jar;
  const response = await fetch(`https://github.com/tlaplus/tlaplus/releases/download/v${TLA.version}/tla2tools.jar`);
  if (!response.ok) fail(`could not download tla2tools.jar ${TLA.version}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (sha256(bytes) !== TLA.sha256) fail(`the downloaded tla2tools.jar ${TLA.version} does not match its pinned sha256`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(jar, bytes);
  return jar;
}

function tlc(jar, work, cfg) {
  const args = ["-XX:+UseParallelGC", "-cp", jar, "tlc2.TLC", "-workers", "auto", "-cleanup", "-metadir", path.join(work, "states", cfg), "-config", cfg, "SpendCap.tla"];
  const result = spawnSync("java", args, { cwd: work, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
  if (result.error) fail(`could not run java (${result.error.message}). Install a Java 11 or later runtime.`);
  const out = `${result.stdout}${result.stderr}`;
  const file = path.join(work, cfg.replace(/\.cfg$/, ".out"));
  writeFileSync(file, out);
  const violated = /Invariant (\w+) is violated/.exec(out)?.[1] ?? null;
  if (!violated && !/Model checking completed\. No error has been found\./.test(out)) fail(`TLC did not finish ${cfg}. Read ${file}`);
  return { violated, states: /([\d,]+) distinct states found, [\d,]+ states left on queue/.exec(out)?.[1] ?? "?", file };
}

const only = process.argv[2];
const build = spawnSync("pnpm", ["exec", "tsc", "-p", "tsconfig.json"], { cwd: repo, stdio: "inherit" });
if (build.status !== 0) fail("the TypeScript build failed");
const work = mkdtempSync(path.join(os.tmpdir(), "whale-spend-cap-"));
for (const name of readdirSync(here)) if (/\.(tla|cfg)$/.test(name)) copyFileSync(path.join(here, name), path.join(work, name));
if (only && existsSync(only)) copyFileSync(only, path.join(work, path.basename(only)));
writeFileSync(path.join(work, "SpendCode.tla"), await spendCode());
const jar = await tlaJar();
let ok = true;
for (const { cfg, expect } of only ? [{ cfg: path.basename(only), expect: null }] : RUNS) {
  const result = tlc(jar, work, cfg);
  const matches = result.violated === expect;
  ok &&= matches;
  console.log(`${matches ? "ok  " : "FAIL"} ${cfg}: ${result.violated ? `${result.violated} is violated` : "every invariant holds"} (${result.states} distinct states) ${result.file}`);
  if (!matches) console.log(expect ? `     expected ${expect} to be violated by an open finding. If its fix landed, follow SKILL.md "Intended changes".` : "     expected every invariant to hold. Read the counterexample in the file above.");
}
console.log(`model and generated SpendCode.tla: ${work}`);
process.exit(ok ? 0 : 1);
